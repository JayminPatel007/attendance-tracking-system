package org.sabha.sabha.domain;

/**
 * The track dimension of a {@link SabhaKind} (CONTEXT § Bal Sevak Sabha). BSS
 * and YSS are the parallel additive selective programs for the child and youth
 * tiers respectively; REGULAR is the standing track every demographic has.
 */
public enum Track {
    REGULAR,
    BSS,
    YSS
}
